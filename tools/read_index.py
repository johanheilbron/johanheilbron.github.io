#!/usr/bin/env python3
"""
read_index.py: turn Johan's gold Word files into plain-text snapshots.

There are two gold files, both Johan's own and both READ-ONLY for us:
  - the publication index  -> content/publications/index-snapshot.txt
  - the complete CV        -> content/cv-snapshot.txt
This script only ever OPENS THEM FOR READING; it never writes, moves or
renames them. `git diff` on a snapshot shows exactly what changed since the
last sync.

Italic text in Word becomes *italic* (Markdown). One paragraph per line.

Usage:
    uv run tools/read_index.py                write the publication snapshot
    uv run tools/read_index.py --cv           write the CV snapshot
    add --print to print to the screen instead of writing
"""

import re
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

GOLD = Path.home() / "OneDrive" / "Documenten" / "Johan 1 - Werk" / "CV"
REPO = Path(__file__).resolve().parent.parent


def newest(pattern):
    """The CV file name carries a year ("... 2026.docx"); take the newest match."""
    matches = sorted(GOLD.glob(pattern), key=lambda p: p.stat().st_mtime)
    if not matches:
        sys.exit(f"No file matching '{pattern}' in {GOLD}")
    return matches[-1]


if "--cv" in sys.argv:
    INDEX = newest("- 2 Heilbron CV (English complete)*.docx")
    SNAPSHOT = REPO / "content" / "cv-snapshot.txt"
else:
    INDEX = GOLD / "- 1 PUBL78NU(NL).docx"
    SNAPSHOT = REPO / "content" / "publications" / "index-snapshot.txt"

# Snapshots are public (they are committed); never let an e-mail address into them.
EMAIL = re.compile(r"[\w.+-]+@[\w-]+(\.[\w-]+)+")

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def is_italic(run):
    i = run.find(f"{W}rPr/{W}i")
    return i is not None and i.get(W + "val") not in ("0", "false")


def paragraph_text(p):
    parts = []  # (italic, text)
    for run in p.iter(W + "r"):
        text = "".join(t.text or "" for t in run.findall(W + "t"))
        if not text:
            continue
        italic = is_italic(run)
        if parts and parts[-1][0] == italic:
            parts[-1] = (italic, parts[-1][1] + text)
        else:
            parts.append((italic, text))
    out = []
    for italic, text in parts:
        if italic and text.strip():
            lead = text[: len(text) - len(text.lstrip())]
            trail = text[len(text.rstrip()):]
            out.append(f"{lead}*{text.strip()}*{trail}")
        else:
            out.append(text)
    return " ".join("".join(out).split())


def read_index():
    with open(INDEX, "rb") as fh:  # read-only
        root = ET.fromstring(zipfile.ZipFile(fh).read("word/document.xml"))
    lines = [EMAIL.sub("[e-mail address removed]", paragraph_text(p)) for p in root.iter(W + "p")]
    return [line for line in lines if line]


def main():
    lines = read_index()
    text = (
        "# Snapshot of one of Johan's gold Word files, generated by tools/read_index.py.\n"
        f"# Source (read-only): {INDEX}\n"
        "# Do not edit by hand. One paragraph per line; *...* is italic in Word.\n\n"
        + "\n".join(lines) + "\n"
    )
    if "--print" in sys.argv:
        sys.stdout.reconfigure(encoding="utf-8")
        print(text)
    else:
        SNAPSHOT.write_text(text, encoding="utf-8")
        print(f"wrote {SNAPSHOT.relative_to(REPO)} ({len(lines)} paragraphs)")


if __name__ == "__main__":
    main()
