#!/usr/bin/env python3
"""
read_index.py: turn Johan's gold publication index (.docx) into plain text.

The gold index is Johan's own Word file. This script only ever OPENS IT FOR
READING; it never writes, moves or renames it. The text it produces is saved
as content/publications/index-snapshot.txt, so that `git diff` on that file
shows exactly what changed in the index since the last sync.

Italic text in Word becomes *italic* (Markdown). One paragraph per line.

Usage:
    uv run tools/read_index.py             write the snapshot
    uv run tools/read_index.py --print     print to the screen instead
"""

import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

INDEX = Path.home() / "OneDrive" / "Documenten" / "Johan 1 - Werk" / "CV" / "- 1 PUBL78NU(NL).docx"
SNAPSHOT = Path(__file__).resolve().parent.parent / "content" / "publications" / "index-snapshot.txt"

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def is_italic(run):
    i = run.find(f"{W}rPr/{W}i")
    return i is not None and i.get(W + "val") not in ("0", "false")


def paragraph_text(p):
    parts = []  # (italic, text)
    for run in p.iter(W + "r"):
        text = "".join(t.text or "" for t in run.findall(W + "t"))
        if not text:
            continue
        italic = is_italic(run)
        if parts and parts[-1][0] == italic:
            parts[-1] = (italic, parts[-1][1] + text)
        else:
            parts.append((italic, text))
    out = []
    for italic, text in parts:
        if italic and text.strip():
            lead = text[: len(text) - len(text.lstrip())]
            trail = text[len(text.rstrip()):]
            out.append(f"{lead}*{text.strip()}*{trail}")
        else:
            out.append(text)
    return " ".join("".join(out).split())


def read_index():
    with open(INDEX, "rb") as fh:  # read-only
        root = ET.fromstring(zipfile.ZipFile(fh).read("word/document.xml"))
    lines = [paragraph_text(p) for p in root.iter(W + "p")]
    return [line for line in lines if line]


def main():
    lines = read_index()
    text = (
        "# Snapshot of Johan's gold index, generated by tools/read_index.py.\n"
        f"# Source (read-only): {INDEX}\n"
        "# Do not edit by hand. One paragraph per line; *...* is italic in Word.\n\n"
        + "\n".join(lines) + "\n"
    )
    if "--print" in sys.argv:
        sys.stdout.reconfigure(encoding="utf-8")
        print(text)
    else:
        SNAPSHOT.write_text(text, encoding="utf-8")
        print(f"wrote {SNAPSHOT.relative_to(SNAPSHOT.parents[2])} ({len(lines)} paragraphs)")


if __name__ == "__main__":
    main()
